# FINISH / HUD
# ----------------------------------------------------------------------

font = pygame.font.Font(None, 27)
largeFont = pygame.font.Font(None, 40)
titleFont = pygame.font.Font(None, 50)

finishPosition = 0.0


def getRaceTime():
    return raceTime


def drawHUD():
    panel = pygame.Surface((SCREEN_WIDTH, 105), pygame.SRCALPHA)
    panel.fill((10, 10, 10, 225))
    screen.blit(panel, (0, 0))

    title = titleFont.render("CURVE RACE", True, WHITE)
    screen.blit(title, (25, 12))

    time_text = font.render(
        f"TIME: {raceTime:05.1f}s",
        True,
        YELLOW,
    )
    screen.blit(time_text, (270, 20))

    controls = font.render(
        "RIGHT: ACCELERATE    LEFT: BRAKE / REVERSE    ESC: QUIT",
        True,
        WHITE,
    )
    screen.blit(controls, (270, 52))

    # Live race positions.
    y = 88
    for racer in racers:
        progress = min(
            100,
            int((racer.position / finishPosition) * 100)
        )

        text = font.render(
            f"{racer.name}: {progress:3d}%   {racer.speed:3.0f}",
            True,
            racer.color,
        )
        screen.blit(text, (25 + racers.index(racer) * 205, y))


def drawFinishResults():
    if winner is None:
        return

    overlay = pygame.Surface((SCREEN_WIDTH, SCREEN_HEIGHT), pygame.SRCALPHA)
    overlay.fill((0, 0, 0, 150))
    screen.blit(overlay, (0, 0))

    title = titleFont.render(
        f"{winner.name} WINS!",
        True,
        winner.color,
    )
    title_rect = title.get_rect(
        center=(SCREEN_WIDTH // 2, 180)
    )
    screen.blit(title, title_rect)

    sorted_racers = sorted(
        racers,
        key=lambda r: r.finish_time if r.finish_time is not None else 999999
    )

    y = 250
    for index, racer in enumerate(sorted_racers, start=1):
        result = (
            f"{index}. {racer.name}   "
            f"{racer.finish_time:.2f}s   "
            f"Hits: {racer.collision_count}"
        )

        text = font.render(result, True, racer.color)
        rect = text.get_rect(
            center=(SCREEN_WIDTH // 2, y)
        )
        screen.blit(text, rect)
        y += 42

    restart = font.render(
        "Press R to race again    |    ESC to quit",
        True,
        WHITE,
    )
    rect = restart.get_rect(
        center=(SCREEN_WIDTH // 2, y + 25)
    )
    screen.blit(restart, rect)


def drawFrame():
    pygame.draw.rect(
        screen,
        WHITE,
        (4, 4, SCREEN_WIDTH - 8, SCREEN_HEIGHT - 8),
        4,
    )


# ----------------------------------------------------------------------
# MAIN GAME
# ----------------------------------------------------------------------

def resetRace():
    global raceTime, raceStarted, winner
    global cameraX, cameraY, userPosition

    for racer in racers:
        racer.reset()

    createObstacles()

    raceTime = 0.0
    raceStarted = False
    winner = None

    userPosition = START_POSITION

    start_x, start_y, _, _ = getRoadPosition(START_POSITION)

    cameraX = start_x - 250
    cameraY = start_y - 350


def main():
    global raceTime, raceStarted, winner
    global cameraX, cameraY, userPosition

    random.seed()

    createRoad()

    global finishPosition
    finishPosition = road_total_length - 80

    resetRace()

    running = True

    while running:
        dt = clock.tick(60) / 1000.0
        dt = min(dt, 0.05)

        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False

            elif event.type == pygame.KEYDOWN:
                if event.key == pygame.K_ESCAPE:
                    running = False

                if event.key == pygame.K_r and winner is not None:
                    resetRace()

        keys = pygame.key.get_pressed()

        if winner is None:
            if any(keys):
                # The race clock begins as soon as the player starts moving.
                if keys[pygame.K_RIGHT] or keys[pygame.K_LEFT]:
                    raceStarted = True

            if raceStarted:
                raceTime += dt

            player = racers[0]

            if player.stun_timer > 0:
                player.stun_timer -= dt
            else:
                if keys[pygame.K_RIGHT]:
                    player.speed = min(
                        PLAYER_SPEED,
                        player.speed + ACCELERATION * dt
                    )

                elif keys[pygame.K_LEFT]:
                    player.speed = max(
                        -MAX_REVERSE,
                        player.speed - BRAKE * dt
                    )

                else:
                    # Natural rolling slowdown.
                    if player.speed > 0:
                        player.speed = max(0, player.speed - 120 * dt)
                    elif player.speed < 0:
                        player.speed = min(0, player.speed + 120 * dt)

                player.position += player.speed * dt
                player.position = max(
                    START_POSITION,
                    min(player.position, finishPosition)
                )

                updateCheckpoint(player)
                handleCollision(player)

            userPosition = player.position

            updateAI(racers[1], dt)
            updateAI(racers[2], dt)

            # Every racer finishes on the same road; the first to reach
            # the finish line wins by having the shortest race time.
            for racer in racers:
                if not racer.finished and racer.position >= finishPosition:
                    racer.finished = True
                    racer.finish_time = raceTime

                    if winner is None:
                        winner = racer

            # Camera follows the player along the curved world.
            player_x, player_y = getWorldPosition(player.position)

            target_camera_x = player_x - 250
            target_camera_y = player_y - 350

            cameraX += (
                target_camera_x - cameraX
            ) * 7.0 * dt

            cameraY += (
                target_camera_y - cameraY
            ) * 7.0 * dt

        drawRoad()

        drawRaceMarker(
            START_POSITION,
            "START",
            GREEN,
        )

        drawRaceMarker(
            finishPosition,
            "FINISH",
            YELLOW,
        )

        for obstacle in obstacles:
            obstacle.update(dt if winner is None else 0)
            drawObstacle(obstacle)

        # Draw competitors and player directly on the center of the road.
        # There is no lane number and no A/D lane-switching logic.
        for racer in racers[1:]:
            x, y = getWorldPosition(racer.position)
            sx, sy = worldToScreen(x, y)

            pygame.draw.circle(screen, BLACK, (sx, sy), 15)
            pygame.draw.circle(screen, racer.color, (sx, sy), 10)
            pygame.draw.circle(screen, WHITE, (sx, sy), 10, 1)

        player = racers[0]
        x, y = getWorldPosition(player.position)
        sx, sy = worldToScreen(x, y)

        pygame.draw.circle(screen, BLACK, (sx, sy), 16)
        pygame.draw.circle(screen, player.color, (sx, sy), 11)
        pygame.draw.circle(screen, WHITE, (sx, sy), 11, 2)

        drawHUD()
        drawFinishResults()
        drawFrame()

        pygame.display.flip()

    pygame.quit()
    sys.exit()


if __name__ == "__main__":
    main()
